# 2D lists = a list of list / multidimensional list.

drinks = ["coffee", "soda", "tea"]
dinner = ["pizza", "hamburger", "hotdog"]
dessert = ["cake", "ice cream"]

food = [drinks, dinner, dessert]

print(food[0][1])  # first square bracket is for selecting the list you want to display
#                   the second square bracket is for selecting the specific item on that list.
